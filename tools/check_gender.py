def strip_codes(text: str) -> str:
    return CODES.sub("", text or "").replace("\n", " ")


def is_thought(text: str) -> bool:
    """Мысли в скобках обращены к себе — собеседника у них нет."""
    return strip_codes(text).lstrip().startswith("(")


def vocatives(ru: str) -> list[str]:
    """Слова-обращения в реплике, кроме названных в кавычках."""
    quoted = " ".join(QUOTED.findall(ru)).lower()
    found = []
    for m in VOCATIVE.finditer(ru):
        word = m.group(1).lower()
        if word in quoted:
            continue
        found.append(word)
    return found


def addressee(rows: list, i: int, names: dict) -> tuple[str | None, str]:
    """Кому сказана реплика i: имя из текста, иначе сосед по разговору."""
    _key, _file, block, who, ru = rows[i]
    lowered = strip_codes(ru).lower()
    called = {n.lower(): n for n in names.values() if not n.startswith("?")}
    called |= {alias: full for alias, full in ALIASES.items() if full in names.values()}
    for spoken, name in called.items():
        if name == who:
            continue
        if re.search(BOUND_L + r"(?:мисс|миссис|мистер|детектив|прокурор|господин)?\s*"
                     + re.escape(spoken) + BOUND_R, lowered):
            return name, "по имени в реплике"
    for j in range(i - 1, -1, -1):
        if rows[j][2] != block:
            break
        if rows[j][3] and rows[j][3] != who:
            return rows[j][3], "предыдущий говорящий"
    # Реплика открывает блок — собеседник остался в предыдущем. Так Сдобина
    # здоровается с Эджвортом сразу после его мыслей, и без этого шага
    # адресатом считалась Кей, ответившая следующей строкой.
    for j in range(i - 1, max(-1, i - 4), -1):
        if rows[j][1] != rows[i][1]:
            break
        if rows[j][3] and rows[j][3] != who:
            return rows[j][3], "говоривший до блока"
    for j in range(i + 1, len(rows)):
        if rows[j][2] != block:
            break
        if rows[j][3] and rows[j][3] != who:
            return rows[j][3], "следующий говорящий"
    return None, "не определён"


def collect(case: int) -> list:
    """Реплики дела в порядке прохождения: ключ, файл, блок, говорящий, перевод."""
    names = NAMES.get(case, COMMON)
    ru_of = {e["id"]: e.get("ru") or "" for e in load_entries(case)}
    rows = []
    for key, file, who, _seg in R.walk(case):
        block = key.split("|")[1]
        rows.append((key, file, block, names.get(who, who), ru_of.get(key, "")))
    return rows


def marked(text: str, verbs: bool = False) -> list[tuple[str, str, str]]:
    """Что в реплике выдаёт род собеседника: (слово, род, чем оно является)."""
    pairs = [(w, ADDRESS[w], "обращение") for w in vocatives(text)]
    if verbs:
        for rx in (TY_VERB, VERB_BEFORE):
            for m in rx.finditer(text):
                verb = m.group(1).lower()
                pairs.append((verb, "ж" if verb.endswith("ла") else "м",
                              "глагол при «ты»"))
    return pairs


def problems(text: str, who: str, to: str, verbs: bool = False) -> list[tuple[str, str, str]]:
    """Расхождения в одной реплике: род слова против пола адресата."""
    if to not in GENDER:
        return []
    return [p for p in marked(text, verbs)
            if (who, p[0]) not in MASK and p[1] != GENDER[to]]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--case", type=int, choices=CASES, help="одно дело (по умолчанию все)")
    ap.add_argument("--verbs", action="store_true", help="+ род глагола при «ты»")
    ap.add_argument("--list", action="store_true", help="показать словарь обращений")
    args = ap.parse_args()

    if args.list:
        for gender in ("м", "ж"):
            words = [w for w, g in sorted(ADDRESS.items()) if g == gender]
            print(f"{gender}: {', '.join(words)}")
        return 0

    bad: list[tuple[str, str, str, str, str]] = []
    unknown: dict[str, int] = {}
    checked = skipped = 0

    for case in ([args.case] if args.case else list(CASES)):
        names = NAMES.get(case, COMMON)
        rows = collect(case)
        for i, (key, _file, _block, who, ru) in enumerate(rows):
            if not ru or is_thought(ru):
                continue
            text = strip_codes(ru)
            if not marked(text, args.verbs):
                continue
            to, how = addressee(rows, i, names)
            if to is None or to not in GENDER:
                skipped += 1
                if to:
                    unknown[to] = unknown.get(to, 0) + 1
                continue
            checked += 1
            if key in EXCEPT:
                continue
            for word, _gender, kind in problems(text, who, to, args.verbs):
                bad.append((key, word, kind, f"{who} → {to} ({GENDER[to]})",
                            f"{how}: {text[:70]}"))

    for key, word, kind, to, note in bad:
        print(f"{key}\n    {kind} «{word}» — а сказано это {to}\n    {note}")
    if unknown:
        top = ", ".join(f"{n}×{c}" for n, c in sorted(unknown.items(), key=lambda p: -p[1])[:8])
        print(f"\nпол не задан у адресатов: {top}")
    print(f"\nсверено {checked} мест, пропущено {skipped} (адресат не опознан), "
          f"исключений {len(EXCEPT)}")
    if bad:
        print(f"РАСХОЖДЕНИЙ: {len(bad)} — либо править перевод, либо строка "
              f"в EXCEPT с причиной и в docs/decisions.md")
        return 1
    print("OK — род обращений сходится с полом адресата.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
