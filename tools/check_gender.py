# Слово-маска: персонаж зовёт так всех подряд, и пол собеседника ни при чём.
# Заводить строку сюда можно **только** вместе со строкой в docs/decisions.md —
# ровно как DECIDED в check_address.py.
MASK: dict[tuple[str, str], str] = {
    ("Лястраж", "милочка"):
        "приторная любезность ко всем без разбора — decisions.md, «Лястраж → всем»",
}

# Обращение стоит особняком: слева начало реплики или знак, справа знак или конец.
# «Ох, милая шляпка!» так не попадётся, а «Ох, милая!» и «Да, голубчик!» — да.
BOUND_L = r"(?:^|[,!?.…:;—–-]\s*|\(\s*)"
BOUND_R = r"(?=\s*(?:$|[,!?.…:;—–-]))"
WORDS = "|".join(sorted(ADDRESS, key=len, reverse=True))
VOCATIVE = re.compile(
    BOUND_L + r"(?:ах\s+|ох\s+|эй\s+|ну\s+|да\s+|нет\s+|мой\s+|моя\s+)?"
    r"(" + WORDS + r")" + BOUND_R, re.I)

# «Тут „голубушка“ не годится» — слово названо, а не сказано. Кавычки его снимают.
QUOTED = re.compile(r"[«\"']([^«»\"']{0,40})[»\"']")

CODES = re.compile(r"\{[^}]*\}")
# Глагол прошедшего времени рядом с «ты»: «ты нашёл», «нашла ли ты», «ты не спал».
TY_VERB = re.compile(r"\bты\b(?:\s+(?:не|уж|же|ли|бы|тут|там|так|уже|ещё|всё|вообще|точно))*"
                     r"\s+([а-яё]{3,}?(?:л|ла))\b", re.I)
VERB_BEFORE = re.compile(r"\b([а-яё]{3,}?(?:л|ла))\s+(?:ли\s+)?ты\b", re.I)

# Места, где несовпадение намеренно. Заводить строку сюда можно **только**
# вместе со строкой в docs/decisions.md — иначе через месяц исключение уже
# не отличить от забытой ошибки.
