"""Род обращения — сверить с полом того, к кому обращаются.

По-английски обращение рода не имеет: `dearie`, `dear`, `love`, `kid`, `pal` —
одно слово и мужчине, и женщине. Русский обязан выбрать род, а выбор держится
на **адресате**, то есть на том, чего в самой реплике нет: в тексте записан
только говорящий (код E101), собеседник в него не записан.

Так и прошла ошибка дела 3, которую нашёл игрок: `dearie` Сдобиной перевели
«голубчик» — верно для Грегори, Бадда и Эджворта, но тем же словом она зовёт
Молотову, а Кей передразнивает её, обращаясь к самой Сдобиной. Три женских
адресата получили мужское обращение.

Почему это не поймала ни одна проверка и ни одна вычитка:

* `check_len.py` смотрит длину и коды — «голубчик» и «голубушка» одинаково целы;
* `find_idioms.py` ищет кальки — здесь не калька, слово живое и уместное;
* `reread.py` (скилл `/proofread`) выкладывает реплики **одного говорящего**
  подряд, и двадцать «голубчиков» Сдобиной в такой колонке читаются как ровная
  речевая маска. Ошибка видна только в разрезе «реплика ↔ адресат», а такого
  разреза в проекте не было вовсе.

Это тот же класс, что `check_address.py` («ты» или «вы»): **грамматическая
категория, которой в оригинале нет и которую переводчик достраивает из сцены.**
Английский её не выражает — значит, сверять не с чем, и ошибка выходит тихая.

Адресат берётся из хода разговора: ближайшая предыдущая реплика другого
говорящего внутри блока (если реплика первая — ближайшая следующая). Имя
собеседника, названное в самой реплике, перебивает этот порядок.

    python tools/check_gender.py                 # вся игра
    python tools/check_gender.py --case 3        # одно дело
    python tools/check_gender.py --verbs         # + «ты сделал» вместо «сделала»
    python tools/check_gender.py --list          # что считается обращением

Проверка **валится**: в отличие от `check_address.py`, признак здесь не
вероятностный — пол персонажа известен точно. Ложное место (обращение к третьему
лицу, цитата слова, обращение к предмету) заносится в `EXCEPT` **с причиной**,
как `DECIDED` в `check_address.py`.

Чего проверка не покрывает — это надо помнить, а не считать закрытым:

* обращение не к персонажу (статуя, зал, зверь) — адресата нет в `NAMES`;
* число: «а, Рыбы!» по-русски множественное, и «твоему» там брак не по роду;
* род глагола вне связки с «ты» — только с `--verbs`, и только рядом с «ты».
"""
