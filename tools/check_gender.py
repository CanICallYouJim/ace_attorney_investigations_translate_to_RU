def unnamed(key: str) -> tuple[str, str] | None:
    """Кто скрыт за «???» в этой реплике: (кто, пол в глазах собеседника)."""
    file, block, idx = key.split("|")
    for span, (person, seen, _why) in UNNAMED.items():
        s_file, s_block, s_range = span.split("|")
        lo, _, hi = s_range.partition("-")
        if (s_file, s_block) == (file, block) and int(lo) <= int(idx) <= int(hi or lo):
            return person, seen
    return None


# Опознанный «???» получает метку «??? (кто)», пол у метки — из UNNAMED.
