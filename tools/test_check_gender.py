"""Проверка проверки: ловит ли `check_gender.py` то, ради чего заведён.

Сторож, который молча перестал сторожить, хуже отсутствующего: отчёт «OK» читают
как «место чистое». Поэтому здесь лежат сами реплики, ушедшие в игру с чужим
родом 25 августа 2026, — в том виде, в каком их увидел игрок. Если проверка
перестанет их различать (слово выпало из словаря, разъехалась звательная
позиция, сломался разбор кавычек), тест упадёт.

Вторая половина — обратная: фразы, которые ошибкой **не** являются и уже давали
ложные срабатывания. «Прости, лапушка» детективу Бадду, «дорогуша» Лястраж
Эджворту, цитата слова в кавычках. Проверка, которая валится на верном тексте,
проживёт ровно до первого «ну и ладно, отключу».

    PYTHONIOENCODING=utf-8 .venv/Scripts/python.exe tools/test_check_gender.py
"""
from __future__ import annotations

import sys

from check_gender import ADDRESS, GENDER, MASK, addressee, problems, vocatives

# (реплика, говорящий, адресат) — то, что было в игре и оказалось браком.
CAUGHT = [
    ("Так мне и положено, голубчик!", "Сдобина", "Молотова"),
    ("Нет, голубчик! Ну, ничего особенного!", "Кей", "Сдобина"),
    ("Вот именно, милый! А я вот кондитер", "Сдобина", "Кей"),
    ("Кто вам такое право дал, а, дружище!?", "Гамшу", "Нидлер"),
    ("Здравствуй, голубушка! Всё расследуешь, да?", "Сдобина", "Эджворт"),
]

# То же после правки — брака нет.
FIXED = [
    ("Так мне и положено, голубушка!", "Сдобина", "Молотова"),
    ("Нет, голубушка! Ну, ничего особенного!", "Кей", "Сдобина"),
    ("Вот именно, милая! А я вот кондитер", "Сдобина", "Кей"),
    ("Кто вам такое право дал, а, дамочка!?", "Гамшу", "Нидлер"),
    ("Здравствуй, голубчик! Всё расследуешь, да?", "Сдобина", "Эджворт"),
]

# Верный текст, на котором проверка обязана молчать.
CLEAN = [
    ("Ийк! Прости, лапушка, правда прости!", "Сдобина", "Бадд"),        # общий род
    ("Ах, милочка, ну не прелесть ли вы?", "Лястраж", "Эджворт"),        # маска, MASK
    ("Простите, дорогуша, но без улики — никак!", "Лястраж", "Эджворт"),  # общий род
    ("Глупышка! Тут «голубушка» не годится.", "Сдобина", "Кей"),         # слово в кавычках
    ("Ах да, милый! Конечно, откусила!", "Сдобина", "Грегори"),
    ("(Она явно лжёт. Милая женщина, но лжёт.)", "Эджворт", "Кей"),      # не обращение
]

# Адресат из хода разговора: строки вида (ключ, файл, блок, говорящий, реплика).
ROWS = [
    ("f|A|0", "f", "A", "Эджворт", "(Но улик, чтобы это доказать, у меня пока нет...)"),
    ("f|B|0", "f", "B", "Сдобина", "Здравствуй, голубчик!"),
    ("f|B|1", "f", "B", "Кей", "Нет, голубушка!"),
    ("f|B|2", "f", "B", "Защитин", "Майлз, родной. Кошкой тут и не пахнет..."),
]
NAMES_STUB = {"0000": "Эджворт", "0002": "Кей", "001F": "Сдобина", "000B": "Защитин"}


def main() -> int:
    bad: list[str] = []

    for text, who, to in CAUGHT:
        if not problems(text, who, to):
            bad.append(f"НЕ ПОЙМАНО: «{text}» — {who} → {to} ({GENDER[to]})")

    for text, who, to in FIXED:
        found = problems(text, who, to)
        if found:
            bad.append(f"ЛОЖНОЕ на исправленном: «{text}» — {found}")

    for text, who, to in CLEAN:
        found = problems(text, who, to)
        if found:
            bad.append(f"ЛОЖНОЕ: «{text}» — {who} → {to}, зацепилось {found}")

    # Реплика открывает блок: собеседник остался в предыдущем.
    to, how = addressee(ROWS, 1, NAMES_STUB)
    if to != "Эджворт":
        bad.append(f"адресат после смены блока: ожидался Эджворт, вышел {to} ({how})")
    # Ответ внутри блока — предыдущему говорящему.
    to, _ = addressee(ROWS, 2, NAMES_STUB)
    if to != "Сдобина":
        bad.append(f"адресат ответа: ожидалась Сдобина, вышла {to}")
    # Имя вместо фамилии перебивает порядок реплик.
    to, how = addressee(ROWS, 3, NAMES_STUB)
    if to != "Эджворт":
        bad.append(f"«Майлз» должен указать на Эджворта, вышло {to} ({how})")

    # Обращение в кавычках — это упоминание слова, а не обращение.
    if vocatives("Тут «голубушка» не годится, тут скорее «ягнёночек»"):
        bad.append("слово в кавычках принято за обращение")
    # Прилагательное перед существительным — не обращение.
    if vocatives("Ох, милая шляпка!"):
        bad.append("«милая шляпка» принята за обращение")

    # Словарь не должен противоречить сам себе.
    for (who, word) in MASK:
        if word not in ADDRESS:
            bad.append(f"MASK ссылается на слово вне ADDRESS: {word}")

    for line in bad:
        print(line)
    print(f"\nслучаев: {len(CAUGHT)} ловится, {len(FIXED)} исправлено, "
          f"{len(CLEAN)} чистых, адресат по разговору — 3")
    if bad:
        print(f"ПРОВАЛОВ: {len(bad)}")
        return 1
    print("OK — проверка ловит своё и молчит на верном тексте.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
